/**
 * Read and append the PR handoff ledger (MYK9-1397).
 *
 *   node --import tsx scripts/cloud/handoff-cli.ts read --pr=<n>
 *   node --import tsx scripts/cloud/handoff-cli.ts append --pr=<n> --event=<file.json>
 *
 * `read` is GET-only. `append` scans the event, re-reads the ledger, refuses
 * a stale or duplicate event, and only then writes one comment. Both work
 * the same from the Mac and from a cloud checkout; gh resolves the repository
 * from the current checkout.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import {
  artifactKey,
  formatEventComment,
  ledgerTip,
  parseEventComments,
  prepareAppend,
  reconcileHandoff,
  type EventComment,
  type HandoffEvent,
  type LiveState,
  type Reconciliation,
} from './handoff.ts';
import { scanForPublication } from './publication-scan.ts';

/** Runs `gh` with the given arguments and returns stdout; throws a `GhError` on failure. */
export type Gh = (args: string[], input?: string) => string;

/**
 * A failed gh call. `httpStatus` is the status GitHub answered with, or null
 * when gh never got an answer (network, timeout, not installed). Only a
 * confirmed 404 is read as "this record no longer exists"; every other failure
 * stays a failure, so an auth or network problem never reads as missing.
 */
export class GhError extends Error {
  constructor(
    message: string,
    readonly httpStatus: number | null
  ) {
    super(message);
    this.name = 'GhError';
  }
}

/** gh prints `gh: <message> (HTTP <status>)` on stderr when GitHub answered. */
export function ghFailure(args: string[], exitStatus: number | null, stderr: string): GhError {
  const status = /\(HTTP (\d{3})\)/.exec(stderr)?.[1];
  return new GhError(
    `gh ${args[1] ?? ''} failed (exit ${exitStatus})`,
    status === undefined ? null : Number(status)
  );
}

/** The parsed response, or null when GitHub confirmed the record is gone. */
function jsonUnlessGone<T>(gh: Gh, args: string[]): T | null {
  try {
    return json<T>(gh, args);
  } catch (error) {
    if (error instanceof GhError && error.httpStatus === 404) return null;
    throw error;
  }
}

const CLAUDE_FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

type RawComment = { body: string; author_association: string };
type RawPull = { state: string; merged_at: string | null; head: { sha: string } };
type RawArtifact = {
  name: string;
  expired: boolean;
  digest?: string | null;
  workflow_run?: { id: number; head_sha: string };
};
type RawRun = { status: string };

function json<T>(gh: Gh, args: string[]): T {
  return JSON.parse(gh(args)) as T;
}

function readComments(gh: Gh, pr: number): EventComment[] {
  const pages = json<RawComment[][]>(gh, [
    'api',
    '--paginate',
    '--slurp',
    `repos/{owner}/{repo}/issues/${pr}/comments`,
  ]);
  return pages.flat().map(c => ({ body: c.body, authorAssociation: c.author_association }));
}

const RUN_URL = /\/actions\/runs\/(\d+)/;

function readLiveState(gh: Gh, pr: number, latest: HandoffEvent | null): LiveState {
  const pull = json<RawPull>(gh, ['api', `repos/{owner}/{repo}/pulls/${pr}`]);
  const artifacts: LiveState['artifacts'] = {};
  for (const pointer of latest?.evidence ?? []) {
    if (pointer.kind !== 'artifact' || !latest) continue;
    // Every page, or evidence past the first reads as missing. A deleted run
    // takes its artifacts with it: that evidence is missing.
    const pages = jsonUnlessGone<{ artifacts: RawArtifact[] }[]>(gh, [
      'api',
      '--paginate',
      '--slurp',
      `repos/{owner}/{repo}/actions/runs/${pointer.runId}/artifacts`,
    ]);
    const named = (pages ?? [])
      .flatMap(page => page.artifacts)
      .filter(artifact => artifact.name === pointer.name);
    // The digest binds the content; run and head bind it to this review. The
    // artifacts API exposes no attempt, so the digest is what tells a
    // re-uploaded replacement apart. No digest means unverifiable.
    const exact = named.find(
      artifact =>
        typeof artifact.digest === 'string' &&
        artifact.digest === pointer.digest &&
        String(artifact.workflow_run?.id) === pointer.runId &&
        artifact.workflow_run?.head_sha === latest.headSha
    );
    artifacts[artifactKey(pointer)] = exact
      ? exact.expired
        ? 'expired'
        : 'available'
      : named.length > 0
        ? 'mismatched'
        : 'missing';
  }
  // Only an Actions run can be asked whether it ended; a session URL stays unknown.
  const runId = latest ? RUN_URL.exec(latest.ownerUrl)?.[1] : undefined;
  let ownerRun: LiveState['ownerRun'] = 'unknown';
  if (runId) {
    const run = jsonUnlessGone<RawRun>(gh, ['api', `repos/{owner}/{repo}/actions/runs/${runId}`]);
    ownerRun = run === null ? 'gone' : run.status === 'completed' ? 'ended' : 'running';
  }
  return {
    prState: pull.merged_at ? 'merged' : pull.state === 'closed' ? 'closed' : 'open',
    headSha: pull.head.sha,
    artifacts,
    ownerRun,
  };
}

export function readHandoff(
  gh: Gh,
  pr: number
): Reconciliation & { rejected: number; invalid: number } {
  const { events, rejected, invalid } = parseEventComments(readComments(gh, pr), { pr });
  const live = readLiveState(gh, pr, ledgerTip(events));
  return { ...reconcileHandoff(events, live, { invalidRecords: invalid }), rejected, invalid };
}

export async function appendHandoff(
  gh: Gh,
  pr: number,
  event: HandoffEvent,
  env: Record<string, string | undefined>
): Promise<{ posted: boolean; message: string }> {
  if (event.pr !== pr) {
    return { posted: false, message: `wrong PR: event is for ${event.pr ?? 'no PR'}, not #${pr}` };
  }
  const body = formatEventComment(event) + (event.authorHarness === 'claude' ? CLAUDE_FOOTER : '');
  // Same validation a reader applies, so nothing is posted that readers would reject.
  if (parseEventComments([{ body, authorAssociation: 'OWNER' }]).events.length !== 1) {
    return {
      posted: false,
      message: 'invalid event: malformed, or eventId does not match content',
    };
  }
  const scan = await scanForPublication({ dirs: [], texts: [body], env });
  if (!scan.ok) return { posted: false, message: `blocked: ${scan.reason}` };
  const { events, invalid } = parseEventComments(readComments(gh, pr), { pr });
  if (invalid > 0) {
    return { posted: false, message: `invalid ledger: ${invalid} invalid trusted record(s)` };
  }
  const outcome = prepareAppend(events, event);
  if (outcome.kind === 'duplicate') return { posted: false, message: 'duplicate; nothing posted' };
  if (outcome.kind === 'stale') return { posted: false, message: `stale: ${outcome.reason}` };
  gh(
    ['api', '--method', 'POST', `repos/{owner}/{repo}/issues/${pr}/comments`, '--input', '-'],
    JSON.stringify({ body })
  );
  return { posted: true, message: `posted ${event.eventId}` };
}

const realGh: Gh = (args, input) => {
  const result = spawnSync('gh', args, { encoding: 'utf8', input, timeout: 60_000 });
  if (result.error) throw new GhError(`gh could not run: ${result.error.message}`, null);
  if (result.status !== 0) throw ghFailure(args, result.status, result.stderr ?? '');
  return result.stdout;
};

function argValue(args: string[], name: string): string | undefined {
  return args.find(arg => arg.startsWith(`--${name}=`))?.slice(name.length + 3);
}

export async function runCli(args: string[] = process.argv.slice(2), gh: Gh = realGh) {
  const [command] = args;
  const pr = Number(argValue(args, 'pr'));
  if (!Number.isInteger(pr) || pr <= 0) {
    console.error('handoff: --pr=<number> is required');
    return 2;
  }
  if (command === 'read') {
    console.log(JSON.stringify(readHandoff(gh, pr), null, 2));
    return 0;
  }
  if (command === 'append') {
    const file = argValue(args, 'event');
    if (!file) {
      console.error('handoff: append needs --event=<file.json>');
      return 2;
    }
    const event = JSON.parse(readFileSync(file, 'utf8')) as HandoffEvent;
    const result = await appendHandoff(gh, pr, event, process.env);
    console.log(result.message);
    return result.posted ? 0 : 1;
  }
  console.error('handoff: usage: read|append --pr=<n> [--event=<file.json>]');
  return 2;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  // No top-level await: the root package is CommonJS, so tsx compiles this file as CJS.
  void runCli().then(code => {
    process.exitCode = code;
  });
}
