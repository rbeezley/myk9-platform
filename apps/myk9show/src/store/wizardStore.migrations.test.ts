import { describe, expect, it } from 'vitest';
import { migrateWizardState, WIZARD_STORE_VERSION } from './wizardStore.migrations';

describe('wizard store migration', () => {
  it('converts exact legacy generated labels to derived names', () => {
    const migrated = migrateWizardState(
      {
        trials: [
          {
            id: 'generated',
            name: 'Saturday Trial 2',
            trialDate: '2026-08-01',
            startTimeDraft: '08:00 AM',
          },
          {
            id: 'generated-marker',
            name: 'Summer Classic',
            autoGeneratedName: true,
            trialDate: '2026-08-01',
            startTimeDraft: '10:00 AM',
          },
        ],
      },
      0
    ) as { trials: Array<Record<string, unknown>> };

    expect(migrated.trials).toEqual([
      { id: 'generated', trialDate: '2026-08-01', startTimeDraft: '08:00 AM' },
      { id: 'generated-marker', trialDate: '2026-08-01', startTimeDraft: '10:00 AM' },
    ]);
  });

  it('preserves every non-generated legacy name as an explicit override', () => {
    const migrated = migrateWizardState(
      {
        trials: [
          { id: 'custom', name: 'Novice Scent Work', trialDate: '2026-08-01' },
          { id: 'near-match', name: 'Saturday Trial 2 - Novice', trialDate: '2026-08-01' },
        ],
      },
      0
    ) as { trials: Array<Record<string, unknown>> };

    expect(migrated.trials).toEqual([
      { id: 'custom', trialDate: '2026-08-01', nameOverride: 'Novice Scent Work' },
      {
        id: 'near-match',
        trialDate: '2026-08-01',
        nameOverride: 'Saturday Trial 2 - Novice',
      },
    ]);
  });

  it('leaves drafts at the current version untouched', () => {
    const persisted = { trials: [{ id: 'one', nameOverride: 'Custom' }] };

    expect(migrateWizardState(persisted, WIZARD_STORE_VERSION)).toBe(persisted);
  });

  describe('v3: check and cash on for a new show (MYK9-1799)', () => {
    const offShow = { name: '', acceptCheckPayments: false, acceptCashPayments: false };

    it('gives a still-blank saved draft the new defaults', () => {
      const migrated = migrateWizardState({ show: offShow, trials: [] }, 2) as {
        show: typeof offShow;
      };

      expect(migrated.show.acceptCheckPayments).toBe(true);
      expect(migrated.show.acceptCashPayments).toBe(true);
    });

    it('leaves a draft she has named exactly as she left it', () => {
      const persisted = { show: { ...offShow, name: 'Fall Classic' }, trials: [] };

      expect(migrateWizardState(persisted, 2)).toBe(persisted);
    });

    it('leaves a draft that already has a trial exactly as she left it', () => {
      const persisted = { show: offShow, trials: [{ id: 'one', trialDate: '2026-10-10' }] };

      expect(migrateWizardState(persisted, 2)).toBe(persisted);
    });

    it('applies after the older trial-name migration, in one pass from v0', () => {
      const migrated = migrateWizardState({ show: offShow, trials: [] }, 0) as {
        show: typeof offShow;
      };

      expect(migrated.show.acceptCheckPayments).toBe(true);
    });
  });
});
