-- MYK9-2044: the registry recording fee as a dated rate list a site admin edits.
--
-- The AKC recording fee (per entry) was a hardcoded year table in
-- akcTrialSecretaryReportPolicy.ts (2025 and 2026 only) and the premium printed no
-- recording fee at all (AKC Ch. 3 s.15: "AKC recording fee shall be stated"). A row here is
-- "from this date, this registry charges this many cents per entry". The rate in force for a
-- show is the row with the latest effective_from on or before the show's date; no such row
-- means no rate (the report fails closed and the premium prints no line; never guessed).
-- Read by the Trial Secretary report (app) and generate-premium (edge function), so the two
-- cannot disagree. A future AKC change is a new row on /admin/payouts, with no deploy.
--
-- Seed (AKC), amounts in integer cents. Source for all three rows: AKC Secretary's Page,
-- September 2025, p. 28 (Board executive session: the event service fee goes from $3.50 to
-- $4.50 per entry on January 1, 2026 and to $5.50 on January 1, 2027).
--   2025-01-01  350
--   2026-01-01  450
--   2027-01-01  550
-- UKC and ASCA are accepted by the table and seeded with nothing.
--
-- Access:
--   * authenticated: SELECT (secretaries run the report and generate the premium under their
--     own session; the generate-premium function reads through the caller's client).
--   * site admins (is_site_admin()): INSERT / UPDATE / DELETE, by RLS. The admin page only
--     adds rows; UPDATE and DELETE are granted so a typo can be corrected from the SQL editor
--     or a later UI without another migration.
--   * service_role: ALL.
--   * anon: NO access (explicit REVOKE; default privileges here grant anon full CRUD on new
--     tables). The public premium is generated by the edge function, not read by anon, so
--     anon needs nothing.
--
-- NOT PUSHED by the authoring agent.

BEGIN;

CREATE TABLE IF NOT EXISTS public.registry_recording_fee_rates (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  registry text NOT NULL,
  effective_from date NOT NULL,
  amount_cents integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users (id) ON DELETE SET NULL DEFAULT auth.uid(),
  CONSTRAINT registry_recording_fee_rates_registry_check
    CHECK (registry IN ('AKC', 'UKC', 'ASCA')),
  CONSTRAINT registry_recording_fee_rates_amount_check
    CHECK (amount_cents >= 0 AND amount_cents <= 100000),
  CONSTRAINT registry_recording_fee_rates_registry_effective_from_key
    UNIQUE (registry, effective_from)
);

COMMENT ON TABLE public.registry_recording_fee_rates IS
  'MYK9-2044: dated per-entry recording fee by registry. Rate in force for a date = latest effective_from on or before it; none = no rate. Edited on /admin/payouts.';
COMMENT ON COLUMN public.registry_recording_fee_rates.amount_cents IS
  'Recording fee per entry, integer cents.';
COMMENT ON COLUMN public.registry_recording_fee_rates.effective_from IS
  'Calendar date (no timezone) the rate starts to apply; compared against the show/trial date as written.';

ALTER TABLE public.registry_recording_fee_rates ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.registry_recording_fee_rates FORCE ROW LEVEL SECURITY;

REVOKE ALL ON public.registry_recording_fee_rates FROM anon;
REVOKE ALL ON public.registry_recording_fee_rates FROM authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.registry_recording_fee_rates TO authenticated;
GRANT ALL ON public.registry_recording_fee_rates TO service_role;

CREATE POLICY registry_recording_fee_rates_select
  ON public.registry_recording_fee_rates
  FOR SELECT TO authenticated
  USING (true);

CREATE POLICY registry_recording_fee_rates_insert
  ON public.registry_recording_fee_rates
  FOR INSERT TO authenticated
  WITH CHECK ((SELECT public.is_site_admin()));

CREATE POLICY registry_recording_fee_rates_update
  ON public.registry_recording_fee_rates
  FOR UPDATE TO authenticated
  USING ((SELECT public.is_site_admin()))
  WITH CHECK ((SELECT public.is_site_admin()));

CREATE POLICY registry_recording_fee_rates_delete
  ON public.registry_recording_fee_rates
  FOR DELETE TO authenticated
  USING ((SELECT public.is_site_admin()));

-- AKC Secretary's Page, September 2025, p. 28 (see header).
INSERT INTO public.registry_recording_fee_rates (registry, effective_from, amount_cents)
VALUES
  ('AKC', DATE '2025-01-01', 350),
  ('AKC', DATE '2026-01-01', 450),
  ('AKC', DATE '2027-01-01', 550)
ON CONFLICT (registry, effective_from) DO NOTHING;

COMMIT;
