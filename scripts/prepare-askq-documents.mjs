// Usage: node scripts/prepare-askq-documents.mjs [--check]
//   --check  write nothing; exit 1 when the committed documentAssets.ts is stale
//            (askqDocumentAssetsFresh.test.ts runs this in CI).
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const outFile = join(repoRoot, 'supabase/functions/_shared/askq/documentAssets.ts');

const guides = [
  ['secretary-guide', 'Secretary Guide', 'Trial secretaries', 'secretary-guide.md'],
  ['exhibitor-guide', 'Exhibitor Guide', 'Dog exhibitors', 'exhibitor-guide.md'],
  [
    'judge-steward-quickstart',
    'Ringside Quickstart',
    'Judges and stewards',
    'judge-steward-quickstart.md',
  ],
  [
    'club-admin-guide',
    'Club Admin & Treasurer Guide',
    'Club admins and treasurers',
    'club-admin-guide.md',
  ],
];

const rulebooks = [
  [
    'akc-scent-work',
    'AKC',
    'akc-scent-work',
    'AKC Scent Work Regulations',
    'akc-scent-work-regulations.txt',
  ],
  ['ukc-nosework', 'UKC', 'ukc-nosework', 'UKC Nose Work Rules', 'ukc-nose-work-rules.txt'],
  [
    'asca-scent-detection',
    'ASCA',
    'asca-scent-detection',
    'ASCA Scent Detection Rules',
    'asca-scent-detection-rules.txt',
  ],
];

function cleanGuide(markdown) {
  let output = markdown;
  const cut = output.search(/\n#{1,3}\s+Screenshot Checklist/i);
  if (cut !== -1) output = output.slice(0, cut);
  output = output.replace(/^\*\*(Status|Audience|Last verified|Verified by):\*\*.*\n/gim, '');
  output = output.replace(/^>\s*\*\*Note:\*\*[\s\S]*?\n\n/m, '');
  return output.trim();
}

async function readGuide([id, title, audience, file]) {
  const content = await readFile(join(repoRoot, 'docs/user-guides', file), 'utf8');
  return { id, title, audience, content: cleanGuide(content) };
}

async function readRulebook([id, organizationCode, sportCode, title, file]) {
  const content = await readFile(join(repoRoot, 'docs/rulebooks', file), 'utf8');
  return { id, organizationCode, sportCode, title, content: content.trim() };
}

async function run() {
  const guideAssets = await Promise.all(guides.map(readGuide));
  const rulebookAssets = await Promise.all(rulebooks.map(readRulebook));

  const raw = `// Generated by scripts/prepare-askq-documents.mjs. Do not edit by hand.
import type { AskQGuideAsset, AskQRulebookAsset } from './documentContext.ts';

export const ASKQ_GUIDES: AskQGuideAsset[] = ${JSON.stringify(guideAssets)};

export const ASKQ_RULEBOOKS: AskQRulebookAsset[] = ${JSON.stringify(rulebookAssets)};
`;
  // Formatted as committed, so a regenerate is a clean diff and --check is a
  // plain string comparison.
  const body = await prettier.format(raw, {
    ...(await prettier.resolveConfig(outFile)),
    filepath: outFile,
  });

  if (process.argv.includes('--check')) {
    const committed = await readFile(outFile, 'utf8').catch(() => '');
    if (committed !== body) {
      console.error(
        '[prepare-askq-documents] documentAssets.ts is stale: a user guide or rulebook changed. ' +
          'Run `pnpm askq:prepare-docs`, commit it, and deploy ask-myk9show.'
      );
      process.exit(1);
    }
    console.log('[prepare-askq-documents] documentAssets.ts is up to date.');
    return;
  }

  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, body);
  console.log(
    `[prepare-askq-documents] ${guideAssets.length} guides + ${rulebookAssets.length} rulebooks written.`
  );
}

run().catch(error => {
  console.error('[prepare-askq-documents] failed:', error);
  process.exit(1);
});
